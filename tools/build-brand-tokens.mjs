#!/usr/bin/env node
// Builds the website's brand layer: colour tokens, plus the logo and font files it
// shares with the app.
//
// The app reads its colours from frontend/src/local/brandPalette.js. The website is
// a separate, framework-free static build with no access to that module at runtime,
// so it gets a generated stylesheet instead of a second hand-typed copy. One source,
// two consumers, no drift.
//
// The logo and font files are copied rather than referenced across directories,
// because the site has to be deployable on its own - it will eventually be served
// from somewhere the app's source tree is not. The copies are refreshed by this
// script, so they cannot fall behind the originals either.
//
// brandPalette.test.mjs guards the generated file the same way it guards the app's
// stylesheets, so a colour cannot be edited into it by hand either.
//
// Run: node tools/build-brand-tokens.mjs

import { copyFileSync, mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import {
  ABSOLUTE,
  ACCENT,
  BRAND,
  CREAM,
  CREAM_DIM,
  GROUND,
  INK,
  SIGNAL,
  brandRgb,
} from "../frontend/src/local/brandPalette.js";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(repoRoot, "website", "src", "tokens.css");

// name -> [value, what it is for]. The comment is the point: a hex tells the next
// person nothing about whether they are allowed to use it.
const TOKENS = [
  ["-- brand", null, "The three colours in the logo, plus its ink"],
  ["green-deep", BRAND.greenDeep, "the logo's deep green"],
  ["green-mid", BRAND.greenMid, "the logo's mid green"],
  ["gold", BRAND.gold, "the logo's gold - correct on paper, muddy on a dark screen"],
  ["cream", CREAM, "the reversed logo's ink"],
  ["cream-dim", CREAM_DIM, "the reversed logo's second ink"],

  ["-- ground", null, "Surfaces, darkest first"],
  ["ground", GROUND.canvas, "the page"],
  ["ground-deep", GROUND.abyss, "behind a sheet, and the deepest shadow"],
  ["panel", GROUND.raised, "a surface lifted off the page"],
  ["panel-high", GROUND.raisedHigh, "a surface lifted off a panel"],
  ["card", GROUND.card, "a product card - the logo's own mid green"],
  ["line", GROUND.border, "a divider"],
  ["line-strong", GROUND.borderStrong, "a divider that has to carry weight"],

  ["-- ink", null, "Text, quietest first"],
  ["ink-faint", INK.faint, "disabled, placeholder"],
  ["ink-muted", INK.muted, "labels, secondary detail"],
  ["ink-body", INK.body, "ordinary reading text"],
  ["ink-bright", INK.bright, "emphasised text"],
  ["ink", INK.brightest, "headings and prices"],

  ["-- accent", null, "Gold means \"this is the action\", and nothing else"],
  ["accent", ACCENT.accent, "the action, on the dark ground"],
  ["accent-bright", ACCENT.bright, "hover and focus"],
  ["accent-deep", ACCENT.deep, "gold on a light surface"],

  ["-- signal", null, "Not brand-coloured on purpose - a warning in the brand's own gold is a warning nobody sees"],
  ["ok", SIGNAL.successBright, "in stock, delivered"],
  ["warn", SIGNAL.attention, "running low"],
  ["danger", SIGNAL.dangerBright, "sold out, failed"],
  ["info", SIGNAL.info, "we could not check"],

  ["-- absolute", null, "Paper and ink, for anything that prints"],
  ["paper", ABSOLUTE.white, "printed background"],
];

// Translucency is where a brand normally leaks: a tint nobody thinks to check.
// These are built from palette colours so they cannot be anything else.
const ALPHAS = [
  ["line-soft", INK.muted, 0.16, "a hairline that should barely register"],
  ["line-hair", INK.muted, 0.1, "the quietest possible divider"],
  ["accent-wash", ACCENT.accent, 0.12, "a gold tint behind an active thing"],
  ["accent-edge", ACCENT.accent, 0.34, "a gold border"],
  ["scrim", GROUND.abyss, 0.66, "behind an open sheet"],
  ["shadow", GROUND.abyss, 0.4, "a cast shadow"],
];

const lines = [
  "/* Generated by tools/build-brand-tokens.mjs from frontend/src/local/brandPalette.js.",
  " * Do not edit - change the palette module and re-run.",
  " *",
  " * The app and this site are the same company, so they read their colours from one",
  " * file. brandPalette.test.mjs fails the build if a colour appears in either",
  " * stylesheet that is not in that file.",
  " */",
  "",
  ":root {",
];

for (const [name, value, note] of TOKENS) {
  if (value === null) {
    lines.push("", `  /* ${note} */`);
    continue;
  }
  lines.push(`  --${name}: ${value}; /* ${note} */`);
}

lines.push("", "  /* Translucent layers, tinted from palette colours only */");
for (const [name, base, alpha, note] of ALPHAS) {
  const rgb = brandRgb(base);
  if (!rgb) throw new Error(`${base} is not a palette colour, so --${name} cannot be built from it`);
  lines.push(`  --${name}: rgba(${rgb.r}, ${rgb.g}, ${rgb.b}, ${alpha}); /* ${note} */`);
}

lines.push("}", "");

writeFileSync(OUT, lines.join("\n"));
console.log(`wrote ${TOKENS.filter(([, v]) => v !== null).length + ALPHAS.length} tokens to website/src/tokens.css`);

// The shared files. Only the reversed logo cuts: this site is dark throughout, and
// the normal cut is deep green, which disappears on it.
const SHARED = [
  ["frontend/public/branding/frooz-logo-reversed.svg", "website/public/branding/frooz-logo-reversed.svg"],
  ["frontend/public/branding/frooz-mark-reversed.svg", "website/public/branding/frooz-mark-reversed.svg"],
  ["frontend/public/branding/frooz-wordmark-reversed.svg", "website/public/branding/frooz-wordmark-reversed.svg"],
  ["frontend/public/favicon.svg", "website/public/branding/favicon.svg"],
  ["frontend/src/assets/fonts/inter-latin.woff2", "website/public/fonts/inter-latin.woff2"],
  ["frontend/src/assets/fonts/inter-latin-ext.woff2", "website/public/fonts/inter-latin-ext.woff2"],
  ["frontend/src/assets/fonts/bodoni-moda-latin.woff2", "website/public/fonts/bodoni-moda-latin.woff2"],
  ["frontend/src/assets/fonts/bodoni-moda-latin-ext.woff2", "website/public/fonts/bodoni-moda-latin-ext.woff2"],
  ["frontend/src/assets/fonts/LICENSE-Inter.txt", "website/public/fonts/LICENSE-Inter.txt"],
  ["frontend/src/assets/fonts/LICENSE-BodoniModa.txt", "website/public/fonts/LICENSE-BodoniModa.txt"],
];

mkdirSync(join(repoRoot, "website", "public", "branding"), { recursive: true });
mkdirSync(join(repoRoot, "website", "public", "fonts"), { recursive: true });
for (const [from, to] of SHARED) copyFileSync(join(repoRoot, from), join(repoRoot, to));
console.log(`refreshed ${SHARED.length} shared brand files under website/public/`);
