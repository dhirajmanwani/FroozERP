CREATE TABLE IF NOT EXISTS inventory_transfers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  global_id VARCHAR(180) NOT NULL UNIQUE,
  dispatch_batch_id BIGINT REFERENCES dispatch_batches(id),
  company_id INTEGER NOT NULL REFERENCES companies(id),
  source_branch_id INTEGER NOT NULL REFERENCES branches(id),
  source_operational_location_id INTEGER NOT NULL REFERENCES operational_locations(id),
  destination_branch_id INTEGER NOT NULL REFERENCES branches(id),
  destination_operational_location_id INTEGER NOT NULL REFERENCES operational_locations(id),
  initiation_mode VARCHAR(40) NOT NULL,
  transfer_number VARCHAR(80) NOT NULL,
  status VARCHAR(40) NOT NULL DEFAULT 'DRAFT',
  state_version INTEGER NOT NULL DEFAULT 1,
  idempotency_key VARCHAR(220) NOT NULL UNIQUE,
  requested_by INTEGER NOT NULL REFERENCES users(id),
  approved_by INTEGER REFERENCES users(id),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (company_id, transfer_number),
  CHECK (source_operational_location_id <> destination_operational_location_id),
  FOREIGN KEY (company_id, source_branch_id, source_operational_location_id)
    REFERENCES operational_locations(company_id, branch_id, id),
  FOREIGN KEY (company_id, destination_branch_id, destination_operational_location_id)
    REFERENCES operational_locations(company_id, branch_id, id)
);

CREATE TABLE IF NOT EXISTS inventory_transfer_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transfer_id BIGINT NOT NULL REFERENCES inventory_transfers(id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES products(id),
  source_lot_id INTEGER NOT NULL REFERENCES inventory_batches(id),
  requested_quantity NUMERIC(14, 3) NOT NULL CHECK (requested_quantity > 0),
  approved_quantity NUMERIC(14, 3) NOT NULL DEFAULT 0 CHECK (approved_quantity >= 0),
  reserved_quantity NUMERIC(14, 3) NOT NULL DEFAULT 0 CHECK (reserved_quantity >= 0),
  dispatched_quantity NUMERIC(14, 3) NOT NULL DEFAULT 0 CHECK (dispatched_quantity >= 0),
  received_quantity NUMERIC(14, 3) NOT NULL DEFAULT 0 CHECK (received_quantity >= 0),
  rejected_quantity NUMERIC(14, 3) NOT NULL DEFAULT 0 CHECK (rejected_quantity >= 0),
  damaged_quantity NUMERIC(14, 3) NOT NULL DEFAULT 0 CHECK (damaged_quantity >= 0),
  short_quantity NUMERIC(14, 3) NOT NULL DEFAULT 0 CHECK (short_quantity >= 0),
  original_cost_rate NUMERIC(14, 4),
  CHECK (approved_quantity <= requested_quantity),
  CHECK (reserved_quantity <= approved_quantity),
  CHECK (dispatched_quantity <= approved_quantity),
  CHECK (received_quantity + rejected_quantity + damaged_quantity + short_quantity <= dispatched_quantity)
);

