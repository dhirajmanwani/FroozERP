-- Operational-location foundation (additive, protocol v3).
-- This file creates no branch/location rows and performs no ownership backfill.
-- Apply only after a separately approved mapping and backup.

CREATE TABLE IF NOT EXISTS operational_locations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES companies(id),
  branch_id INTEGER NOT NULL REFERENCES branches(id),
  location_code VARCHAR(80) NOT NULL,
  location_name VARCHAR(180) NOT NULL,
  location_type VARCHAR(60) NOT NULL DEFAULT 'STORE',
  address TEXT,
  timezone VARCHAR(80) NOT NULL DEFAULT 'Asia/Kolkata',
  active BOOLEAN NOT NULL DEFAULT TRUE,
  is_default BOOLEAN NOT NULL DEFAULT FALSE,
  deactivated_at TIMESTAMP,
  deactivated_by INTEGER REFERENCES users(id),
  deactivation_reason TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (company_id, branch_id, location_code),
  UNIQUE (company_id, branch_id, id)
);

CREATE UNIQUE INDEX IF NOT EXISTS operational_locations_one_default_idx
  ON operational_locations(company_id, branch_id)
  WHERE is_default = TRUE AND active = TRUE;

